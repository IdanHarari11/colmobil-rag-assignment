import { describe, expect, it } from "vitest";
import type { AsyncStorageLike } from "@assistant-ui/core/react";
import type { TitleGenerationAdapter } from "@assistant-ui/react";
import {
  createOfekThreadListAdapter,
  THREAD_CUSTOM,
} from "./ofek-thread-list-adapter";

function createMemoryStorage(): AsyncStorageLike {
  const map = new Map<string, string>();
  return {
    async getItem(key) {
      return map.has(key) ? (map.get(key) as string) : null;
    },
    async setItem(key, value) {
      map.set(key, value);
    },
    async removeItem(key) {
      map.delete(key);
    },
  };
}

function deferred<T>() {
  let resolve!: (value: T) => void;
  let reject!: (reason?: unknown) => void;
  const promise = new Promise<T>((res, rej) => {
    resolve = res;
    reject = rej;
  });
  return { promise, resolve, reject };
}

const userMessages = [
  {
    role: "user" as const,
    content: [{ type: "text" as const, text: "מה שעות המוקד ביום שישי?" }],
  },
];

describe("ofek thread list adapter timing races", () => {
  it("keeps a manual rename that lands while auto title is still pending", async () => {
    const gate = deferred<string>();
    const titleGenerator: TitleGenerationAdapter = {
      generateTitle: async () => gate.promise,
    };
    const adapter = createOfekThreadListAdapter({
      storage: createMemoryStorage(),
      titleGenerator,
      prefix: "race-manual:",
    });

    const { remoteId } = await adapter.initialize("t-manual");
    const generation = adapter.generateTitle!(remoteId, userMessages as never);

    await adapter.rename(remoteId, "שם ידני בזמן המתנה");
    gate.resolve("כותרת אוטומטית מאוחרת");
    await generation;

    const after = await adapter.fetch(remoteId);
    expect(after.title).toBe("שם ידני בזמן המתנה");
    expect(after.custom?.[THREAD_CUSTOM.titleManuallyEdited]).toBe(true);
  });

  it("does not recreate a thread deleted while title generation is in flight", async () => {
    const gate = deferred<string>();
    const titleGenerator: TitleGenerationAdapter = {
      generateTitle: async () => gate.promise,
    };
    const adapter = createOfekThreadListAdapter({
      storage: createMemoryStorage(),
      titleGenerator,
      prefix: "race-delete:",
    });

    const { remoteId } = await adapter.initialize("t-delete");
    const generation = adapter.generateTitle!(remoteId, userMessages as never);

    await adapter.delete(remoteId);
    gate.resolve("כותרת שלא אמורה להישמר");
    await generation;

    const listed = await adapter.list();
    expect(listed.threads.find((t) => t.remoteId === remoteId)).toBeUndefined();
    await expect(adapter.fetch(remoteId)).rejects.toThrow();
  });

  it("falls back when title generation fails and leaves thread writable for ask path", async () => {
    const titleGenerator: TitleGenerationAdapter = {
      generateTitle: async () => {
        throw new Error("title API down");
      },
    };
    const adapter = createOfekThreadListAdapter({
      storage: createMemoryStorage(),
      titleGenerator,
      prefix: "race-fail:",
    });

    const { remoteId } = await adapter.initialize("t-fail");
    await adapter.generateTitle!(remoteId, userMessages as never);

    const after = await adapter.fetch(remoteId);
    expect(after.title).toBeTruthy();
    expect(after.title).not.toBe("כותרת אוטומטית מאוחרת");
    expect(String(after.title)).toMatch(/שעות|מוקד|שישי/);
    expect(after.custom?.[THREAD_CUSTOM.titleAutoGenerated]).toBe(true);

    // Thread remains listable — ask path can still persist against it.
    const listed = await adapter.list();
    expect(listed.threads.some((t) => t.remoteId === remoteId)).toBe(true);
  });

  it("keeps titles isolated across threads when generation finishes out of order", async () => {
    const gateA = deferred<string>();
    const gateB = deferred<string>();
    const titleGenerator: TitleGenerationAdapter = {
      generateTitle: async (messages) => {
        const text = messages
          .map((m) =>
            m.content
              .filter(
                (part): part is { type: "text"; text: string } =>
                  part.type === "text",
              )
              .map((part) => part.text)
              .join(""),
          )
          .join("");
        if (text.includes("מוקד")) return gateA.promise;
        return gateB.promise;
      },
    };
    const adapter = createOfekThreadListAdapter({
      storage: createMemoryStorage(),
      titleGenerator,
      prefix: "race-switch:",
    });

    const a = await adapter.initialize("thread-a");
    const b = await adapter.initialize("thread-b");

    const genA = adapter.generateTitle!(a.remoteId, [
      {
        role: "user",
        content: [{ type: "text", text: "שאלה על מוקד שישי" }],
      },
    ] as never);
    const genB = adapter.generateTitle!(b.remoteId, [
      {
        role: "user",
        content: [{ type: "text", text: "שאלה על ביטול פוליסה" }],
      },
    ] as never);

    // Finish B first, then A — titles must stay on their remoteIds.
    gateB.resolve("כותרת ביטול");
    await genB;
    gateA.resolve("כותרת מוקד");
    await genA;

    const threadA = await adapter.fetch(a.remoteId);
    const threadB = await adapter.fetch(b.remoteId);
    expect(threadA.title).toBe("כותרת מוקד");
    expect(threadB.title).toBe("כותרת ביטול");
  });
});
