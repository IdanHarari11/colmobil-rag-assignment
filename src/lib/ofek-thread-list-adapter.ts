"use client";

import {
  createLocalStorageAdapter,
  type AsyncStorageLike,
} from "@assistant-ui/core/react";
import type {
  RemoteThreadListAdapter,
  TitleGenerationAdapter,
} from "@assistant-ui/react";
import { createAssistantStream } from "assistant-stream";
import {
  createBrowserAsyncStorage,
  OFEK_THREAD_STORAGE_PREFIX,
} from "@/lib/local-thread-storage";
import { createOfekTitleGenerationAdapter } from "@/lib/thread-title-adapter";
import {
  DEFAULT_THREAD_TITLE,
  fallbackTitleFromQuestion,
  firstUserTextFromMessages,
} from "@/lib/thread-title";

export type OfekThreadListAdapterOptions = {
  /** Defaults to browser localStorage. Injectable for race tests. */
  storage?: AsyncStorageLike;
  /** Defaults to POST /api/thread-title. Injectable for deferred/failing titles. */
  titleGenerator?: TitleGenerationAdapter;
  prefix?: string;
};

/** Custom metadata keys persisted with each thread in localStorage. */
export const THREAD_CUSTOM = {
  createdAt: "createdAt",
  updatedAt: "updatedAt",
  titleManuallyEdited: "titleManuallyEdited",
  titleAutoGenerated: "titleAutoGenerated",
} as const;

function isManualTitle(custom: Record<string, unknown> | undefined): boolean {
  return custom?.[THREAD_CUSTOM.titleManuallyEdited] === true;
}

function isAutoTitled(custom: Record<string, unknown> | undefined): boolean {
  return custom?.[THREAD_CUSTOM.titleAutoGenerated] === true;
}

function nowIso(): string {
  return new Date().toISOString();
}

/**
 * LocalStorage-backed RemoteThreadListAdapter with:
 * - browser-only persistence (ofek-rag: prefix)
 * - createdAt / updatedAt / titleManuallyEdited flags
 * - at most one automatic title write per thread
 * - manual rename always wins over a late auto title
 */
export function createOfekThreadListAdapter(
  options: OfekThreadListAdapterOptions = {},
): RemoteThreadListAdapter &
  Pick<Required<RemoteThreadListAdapter>, "unarchive"> {
  const storage = options.storage ?? createBrowserAsyncStorage();
  const titleGenerator =
    options.titleGenerator ?? createOfekTitleGenerationAdapter();
  const prefix = options.prefix ?? OFEK_THREAD_STORAGE_PREFIX;
  const base = createLocalStorageAdapter({
    storage,
    prefix,
  });

  /** remoteId → title just applied by auto-generation (runtime may re-rename). */
  const pendingAutoTitles = new Map<string, string>();

  const mergeCustom = async (
    remoteId: string,
    patch: Record<string, unknown>,
  ) => {
    if (!base.updateCustom) return;
    try {
      const current = await base.fetch(remoteId);
      await base.updateCustom(remoteId, {
        ...(current.custom ?? {}),
        ...patch,
        [THREAD_CUSTOM.updatedAt]: nowIso(),
      });
    } catch {
      // Thread may have been deleted — ignore metadata touch failures.
    }
  };

  return {
    ...base,
    async initialize(threadId, options) {
      const createdAt = nowIso();
      return base.initialize(threadId, {
        custom: {
          ...(options?.custom ?? {}),
          [THREAD_CUSTOM.createdAt]: createdAt,
          [THREAD_CUSTOM.updatedAt]: createdAt,
          [THREAD_CUSTOM.titleManuallyEdited]: false,
          [THREAD_CUSTOM.titleAutoGenerated]: false,
        },
      });
    },
    async rename(remoteId, newTitle) {
      await base.rename(remoteId, newTitle);
      const expectedAuto = pendingAutoTitles.get(remoteId);
      if (expectedAuto !== undefined && newTitle === expectedAuto) {
        pendingAutoTitles.delete(remoteId);
        await mergeCustom(remoteId, {
          [THREAD_CUSTOM.titleAutoGenerated]: true,
        });
        return;
      }
      pendingAutoTitles.delete(remoteId);
      await mergeCustom(remoteId, {
        [THREAD_CUSTOM.titleManuallyEdited]: true,
      });
    },
    async generateTitle(remoteId, messages) {
      let thread;
      try {
        thread = await base.fetch(remoteId);
      } catch {
        // Deleted — do not recreate from a late async title.
        return createAssistantStream(() => {});
      }

      if (isManualTitle(thread.custom)) {
        const keep = thread.title?.trim() || DEFAULT_THREAD_TITLE;
        return createAssistantStream((controller) => {
          controller.appendText(keep);
        });
      }

      if (isAutoTitled(thread.custom) && thread.title?.trim()) {
        return createAssistantStream((controller) => {
          controller.appendText(thread.title!);
        });
      }

      const question = firstUserTextFromMessages(messages);
      let title: string;
      try {
        title = await titleGenerator.generateTitle(messages);
      } catch {
        title = fallbackTitleFromQuestion(question);
      }
      if (!title.trim()) {
        title = fallbackTitleFromQuestion(question);
      }

      // Re-check after the async model call — manual rename wins.
      let after;
      try {
        after = await base.fetch(remoteId);
      } catch {
        return createAssistantStream(() => {});
      }
      if (isManualTitle(after.custom)) {
        const keep = after.title?.trim() || DEFAULT_THREAD_TITLE;
        return createAssistantStream((controller) => {
          controller.appendText(keep);
        });
      }

      try {
        pendingAutoTitles.set(remoteId, title);
        await base.rename(remoteId, title);
        await mergeCustom(remoteId, {
          [THREAD_CUSTOM.titleAutoGenerated]: true,
          [THREAD_CUSTOM.titleManuallyEdited]: false,
        });
      } catch {
        pendingAutoTitles.delete(remoteId);
        return createAssistantStream(() => {});
      }

      return createAssistantStream((controller) => {
        controller.appendText(title);
      });
    },
  };
}
