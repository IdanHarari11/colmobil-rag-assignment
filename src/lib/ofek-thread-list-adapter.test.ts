import { beforeEach, describe, expect, it, vi } from "vitest";
import { THREAD_CUSTOM } from "./ofek-thread-list-adapter";

/**
 * Unit tests for manual-title precedence helpers and custom flag semantics.
 * Full adapter I/O is covered indirectly via createLocalStorageAdapter;
 * these tests lock the contract we rely on in the wrapper.
 */

describe("THREAD_CUSTOM flags", () => {
  it("exposes stable keys for persistence", () => {
    expect(THREAD_CUSTOM.titleManuallyEdited).toBe("titleManuallyEdited");
    expect(THREAD_CUSTOM.titleAutoGenerated).toBe("titleAutoGenerated");
    expect(THREAD_CUSTOM.createdAt).toBe("createdAt");
    expect(THREAD_CUSTOM.updatedAt).toBe("updatedAt");
  });
});

describe("manual title precedence contract", () => {
  type ThreadMeta = {
    title?: string;
    custom?: Record<string, unknown>;
  };

  function shouldApplyAutoTitle(thread: ThreadMeta): boolean {
    if (thread.custom?.[THREAD_CUSTOM.titleManuallyEdited] === true) {
      return false;
    }
    if (
      thread.custom?.[THREAD_CUSTOM.titleAutoGenerated] === true &&
      thread.title?.trim()
    ) {
      return false;
    }
    return true;
  }

  function resolveTitleAfterGeneration(
    before: ThreadMeta,
    generated: string,
    lateManual?: string,
  ): string {
    const after: ThreadMeta = lateManual
      ? {
          title: lateManual,
          custom: {
            ...(before.custom ?? {}),
            [THREAD_CUSTOM.titleManuallyEdited]: true,
          },
        }
      : before;

    if (after.custom?.[THREAD_CUSTOM.titleManuallyEdited] === true) {
      return after.title?.trim() || "שיחה חדשה";
    }
    return generated;
  }

  it("skips auto title when manually edited", () => {
    expect(
      shouldApplyAutoTitle({
        title: "שם ידני",
        custom: { [THREAD_CUSTOM.titleManuallyEdited]: true },
      }),
    ).toBe(false);
  });

  it("skips second auto title once already generated", () => {
    expect(
      shouldApplyAutoTitle({
        title: "שעות המוקד",
        custom: { [THREAD_CUSTOM.titleAutoGenerated]: true },
      }),
    ).toBe(false);
  });

  it("allows first auto title on a fresh thread", () => {
    expect(
      shouldApplyAutoTitle({
        custom: {
          [THREAD_CUSTOM.titleManuallyEdited]: false,
          [THREAD_CUSTOM.titleAutoGenerated]: false,
        },
      }),
    ).toBe(true);
  });

  it("keeps late manual rename over generated title", () => {
    expect(
      resolveTitleAfterGeneration(
        { custom: { [THREAD_CUSTOM.titleManuallyEdited]: false } },
        "כותרת אוטומטית",
        "כותרת ידנית",
      ),
    ).toBe("כותרת ידנית");
  });

  it("applies generated title when no manual rename intervened", () => {
    expect(
      resolveTitleAfterGeneration(
        { custom: { [THREAD_CUSTOM.titleManuallyEdited]: false } },
        "כותרת אוטומטית",
      ),
    ).toBe("כותרת אוטומטית");
  });
});

describe("local storage quota error messaging", () => {
  beforeEach(() => {
    vi.resetModules();
  });

  it("surfaces quota exceeded instead of silent success", async () => {
    const { createBrowserAsyncStorage } = await import("./local-thread-storage");
    const storage = createBrowserAsyncStorage();

    const original = globalThis.localStorage;
    const fake = {
      getItem: () => null,
      setItem: () => {
        const err = new DOMException("quota", "QuotaExceededError");
        throw err;
      },
      removeItem: () => undefined,
    };
    Object.defineProperty(globalThis, "localStorage", {
      configurable: true,
      value: fake,
    });

    await expect(storage.setItem("ofek-rag:threads", "[]")).rejects.toThrow(
      /quota/i,
    );

    Object.defineProperty(globalThis, "localStorage", {
      configurable: true,
      value: original,
    });
  });
});
